/// Languages of the app. Report content comes from the API in the selected language;
/// this file holds only static interface text.
enum AppLanguage { en, th, pt }

/// App-level language. One controller for every screen; the choice persists in the browser
/// and every API call sends it as `lang`.
class LanguageController extends ChangeNotifier {
  static const _key = 'app_language';
  AppLanguage _language;

  LanguageController({AppLanguage initial = AppLanguage.en}) : _language = initial {
    numberLanguage = code;
  }

  AppLanguage get language => _language;
  String get code => switch (_language) { AppLanguage.th => 'th', AppLanguage.pt => 'pt-BR', AppLanguage.en => 'en' };

  Future<void> load() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString(_key);
      if (saved == 'th' || saved == 'en' || saved == 'pt-BR') {
        _language = saved == 'th' ? AppLanguage.th : saved == 'pt-BR' ? AppLanguage.pt : AppLanguage.en;
        numberLanguage = code;
        notifyListeners();
      }
    } catch (_) {
      // Browser storage can be blocked; English stays.
    }
  }

  Future<void> set(AppLanguage language) async {
    if (language == _language) return;
    _language = language;
    numberLanguage = code;
    notifyListeners();
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_key, code);
    } catch (_) {}
  }

  Future<void> toggle() => set(_language == AppLanguage.en ? AppLanguage.th : AppLanguage.en);

  /// Static text for [key]. `{name}` placeholders take values from [args].
  String t(String key, [Map<String, Object> args = const {}]) {
    var text = code == 'pt-BR' ? (Strings.portuguese[key] ?? Strings.values[key]?['en'] ?? key) : Strings.values[key]?[code] ?? Strings.values[key]?['en'] ?? key;
    args.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
    return text;
  }
}

/// Gives the language controller to the widget tree.
class LanguageScope extends InheritedNotifier<LanguageController> {
  const LanguageScope({super.key, required LanguageController controller, required super.child})
      : super(notifier: controller);

  static LanguageController of(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<LanguageScope>()?.notifier ?? _fallback;

  static final LanguageController _fallback = LanguageController();
}

extension Tr on BuildContext {
  /// Translated static text.
  String tr(String key, [Map<String, Object> args = const {}]) => LanguageScope.of(this).t(key, args);

  /// Language code for API calls.
  String get langCode => LanguageScope.of(this).code;
}

